let LANG = "en";

function pickLanguage(setting) {
  if (setting && I18N[setting]) return setting;
  const sys = (navigator.language || "en").toLowerCase().slice(0, 2);
  return I18N[sys] ? sys : "en";
}

function t(key, params = {}) {
  let s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
}

function tn(key, n, params = {}) {
  const k = n === 1 && I18N[LANG][key + "_one"] ? key + "_one" : key + "_other";
  return t(I18N[LANG][k] || I18N.en[k] ? k : key, { n, ...params });
}

